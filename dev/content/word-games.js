function blankTokens(example, blanks) {
  const chosen = new Set(blanks.map((word) => word.toLowerCase()));
  return example.replace(/[A-Za-z]+/g, (word) => chosen.has(word.toLowerCase()) ? '____' : word);
}

function prepareLesson(chapterId, bandId, source, index) {
  const stage = index + 1;
  const mode = stage === 1 ? 'build' : stage <= 3 ? 'cloze' : 'open';
  const buildWords = tokenize(source.example);
  const targets = mode === 'build' ? unique(buildWords) : unique(source.targets);
  const id = `${chapterId}-${bandId}-${stage}`;
  const blankWords = mode === 'cloze'
    ? (SPECIFIC_BLANKS[id] || source.targets.slice(-(stage === 2 ? 1 : 2)))
    : [];
  return {
    id,
    stage, mode, ...source, targets,
    buildWords: mode === 'build' ? buildWords : [],
    displayText: mode === 'cloze' ? blankTokens(source.example, blankWords) : source.example,
    blankWords,
    blankCount: mode === 'cloze' ? (stage === 2 ? 1 : 2) : 0,
    hintLevel: Math.max(0, 4 - stage),
    words: unique(source.targets).map(wordInfo),
    supportWords: unique(buildWords).filter((word) => !source.targets.includes(word)).map(wordInfo),
    knowledge: source.knowledge,
    alternatives: source.alternatives,
    allowCreative: true,
    goalLabel: mode === 'build' ? '逐词搭一句' : stage === 2 ? '补一个词' : stage === 3 ? '补两个词' : `自由创作 ${stage - 3}`,
  };
}

export const WORD_CHAPTERS = chapterInfo.map((chapter) => ({
  ...chapter,
  words: chapter.words.split(' ').map(wordInfo),
  lessons: Object.fromEntries(WORD_AGE_BANDS.map((band) => [band.id,
    curriculum[chapter.id][band.id].map((source, index) => prepareLesson(chapter.id, band.id, source, index)),
  ])),
}));

/** Exact age is used only to choose a suggested path; any chapter remains available. */
export function getAgeBand(age) {
  const number = Number(age);
  if (!Number.isInteger(number) || number < 3 || number > 10) return null;
  return WORD_AGE_BANDS.find((band) => number >= band.minAge && number <= band.maxAge) || null;
}

export function getChapterLessons(chapterId, age) {
  const band = getAgeBand(age);
  const chapter = WORD_CHAPTERS.find((entry) => entry.id === chapterId);
  return band && chapter ? chapter.lessons[band.id] : [];
}

/** A single invitation per exact age; stable chapter IDs preserve existing saves. */
export function getRecommendedWordChapter(age) {
  const band=getAgeBand(age);
  if(!band)return null;
  const second=band.id==='early'?Number(age)===4:Number(age)===band.maxAge;
  return WORD_CHAPTERS.find(c=>c.id===band.recommended[second?1:0]);
}
export function getWordInspiration(lesson) {
  const swaps={big:['little','blue'],happy:['sleepy','funny'],hands:['feet','eyes'],head:['robot','flower'],red:['blue','green'],blue:['red','yellow'],frog:['duck','robot'],robot:['cat','robot'],flower:['tree','poop'],cat:['pig','robot'],toy:['robot','cat'],jump:['dance','swim']};
  const variants=[];
  for(const [word,replacements] of Object.entries(swaps))if(new RegExp(`\\b${word}\\b`,'i').test(lesson.example)){
    for(const replacement of replacements)variants.push(lesson.example.replace(new RegExp(`\\b${word}\\b`,'i'),replacement));
  }
  return [...new Set([lesson.mode==='cloze'?lesson.displayText:lesson.example,...lesson.alternatives,...variants])].slice(0,4);
}
