const context=()=>({entities:entities(),chapter:'toys'});
apply(planWordIntent('a ball and a box',context()).commands);
const before=runtime.snapshot;
const narration=createWordNarration('Put the ball in the box.',{getContext:context,apply});
narration({status:'playing',start:8,end:12});
assert.equal(log.filter(c=>c.cue==='mention'&&c.id==='wg-ball-0').length,1);
assert.equal(entities()['wg-ball-0'].attachment,undefined);
narration({status:'playing',start:8,end:12});
narration({status:'playing',start:20,end:23});
narration({status:'ended'});
assert.equal(log.filter(c=>c.cue==='put-in').length,1);
assert.equal(log.filter(c=>c.cue==='mention'&&c.id==='wg-box-0').length,1);
assert.equal(Object.keys(entities()).length,2);
assert.deepEqual(entities()['wg-ball-0'].attachment,{target:'wg-box-0',slot:'in'});
assert.deepEqual(runtime.snapshot.progress,before.progress);
const toyNarration=createWordNarration('Put two red balls in the toy box.',{getContext:context,apply});
for(const hit of 'Put two red balls in the toy box.'.matchAll(/[a-z]+/g))toyNarration({status:'playing',start:hit.index,end:hit.index+hit[0].length});
