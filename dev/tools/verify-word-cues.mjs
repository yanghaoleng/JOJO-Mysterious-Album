fx.sync(ball,{id:'ball',attachment:{target:'box',slot:'in'}});fx.cue(ball,{cue:'put-in',target:'box'});
const ys=[];for(let i=0;i<70;i++){fx.update(entries,1/60,i/60,false);ys.push(ball.anchor.position.y);}
assert.ok(Math.max(...ys)>1.4);assert.ok(ys[35]>ys[45]&&ys[45]>ys[55]);assert.equal(ball.wordDrop,null);assert.ok(ball.anchor.position.distanceTo(new THREE.Vector3(1,.084,0))<.001);
fx.cue(ball,{cue:'put-in',target:'box'});fx.update(entries,1/60,3,true);assert.equal(ball.wordDrop,null);assert.ok(Math.abs(ball.anchor.position.y-.084)<1e-6);
fx.cue(ball,{cue:'mention'});fx.cue(ball,{cue:'cancel'});assert.equal(ball.wordCue,null);fx.dispose();
