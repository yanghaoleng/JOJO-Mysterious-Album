assert.deepEqual(runtime.snapshot,snapshot);
const cancelled=createWordNarration('a dog',{getContext:context,apply});cancelled({status:'cancelled'});cancelled({status:'ended'});assert.ok(!entities()['wg-dog-0']);
const make=(id,x)=>{const anchor=new THREE.Group(),group=new THREE.Group();anchor.add(group);anchor.position.set(x,0,0);return {id,anchor,model:{group},scale:.7,modelTop:.6,entrance:2};};
const ball=make('ball',-1),box=make('box',1),entries=new Map([['ball',ball],['box',box]]),fx=createWordEffects();
fx.sync(ball,{id:'ball'});fx.sync(box,{id:'box'});fx.cue(ball,{cue:'mention'});
const heights=[];for(let i=0;i<61;i++){fx.update(entries,1/60,i/60,false);heights.push(ball.cueRoot.position.y);}
