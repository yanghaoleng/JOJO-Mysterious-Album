import assert from 'node:assert/strict';
import { WorldRuntime } from '../runtime/world-runtime.js';
import { capacityEvictions } from '../runtime/contracts.js';
const context = {storyId:'test',sceneId:'test',world:'meadow',actors:[]};
const runtime = new WorldRuntime(); runtime.enter(context);
const batch = start => Array.from({length:100}, (_,i) => ({type:'entity.spawn',id:String(1000-start-i),asset:'prop:apple',position:[0,0],scale:.2}));
for(const start of [0,100,200])assert.ok(runtime.dispatch(batch(start)).ok);
assert.equal(Object.keys(runtime.snapshot.worlds.meadow.entities).length,300);
const old = runtime.snapshot;
assert.equal(capacityEvictions(old.worlds.meadow.entities,batch(300)).length,100);
assert.equal(runtime.dispatch([...batch(300).slice(0,99),{type:'entity.spawn',id:'bad',asset:'invalid',position:[0,0]}]).ok,false);
assert.deepEqual(runtime.snapshot,old,'Rejected batch must not remove old objects');
assert.ok(runtime.dispatch(batch(300)).ok);
let entities=runtime.snapshot.worlds.meadow.entities;
assert.equal(Object.keys(entities).length,300);
for(const c of batch(0))assert.ok(!entities[c.id], 'Oldest must be removed, even with numeric IDs');
for(const c of batch(300))assert.ok(entities[c.id]);
const restored = new WorldRuntime({saved:runtime.snapshot}); restored.enter(context);
assert.equal(Object.keys(restored.snapshot.worlds.meadow.entities).length,300);
assert.ok(restored.dispatch(batch(400)).ok);
entities=restored.snapshot.worlds.meadow.entities;
for(const c of batch(100))assert.ok(!entities[c.id], 'Restore preserves FIFO order');
assert.equal(Object.keys(entities).length,300);
assert.ok(restored.dispatch([{...batch(400)[0],color:'#123456'}]).ok);
assert.equal(Object.keys(restored.snapshot.worlds.meadow.entities).length,300,'Replacing an ID must not evict another entity');
console.log('PASS: 300 cap, FIFO overflow, numeric IDs, atomic rejection, restore and same-ID update');
